def _content_differs(data: dict, p: JobProfile) -> bool:
    """内置岗位定义与数据库记录是否有差异（用于增量更新）。"""
    return (
        data["category"] != p.category
        or data.get("summary") != p.summary
        or data.get("description") != p.description
        or list(data.get("tags", [])) != list(p.tags or [])
        or data["professional_dimensions"] != (p.professional_dimensions or [])
        or copy.deepcopy(GENERAL_DIMENSIONS) != (p.general_dimensions or [])
    )


async def seed_job_profiles(db: AsyncSession) -> dict:
    """幂等播种内置岗位画像：

    - 新标题 → 插入；
    - 已存在且 is_builtin=True → 内容有变化时更新（如维度定义扩充、新增岗位调整）；
    - 用户自建（is_builtin=False）同名岗位 → 不覆盖。

    返回 {"added": 新增数, "updated": 更新数}。
    """
    result = await db.execute(select(JobProfile))
    rows = {p.title: p for p in result.scalars().all()}
    added, updated = 0, 0
    for data in BUILTIN_JOB_PROFILES:
        p = rows.get(data["title"])
        if p is None:
            db.add(JobProfile(
                title=data["title"],
                category=data["category"],
                summary=data.get("summary"),
                description=data.get("description"),
                tags=data.get("tags", []),
                professional_dimensions=data["professional_dimensions"],
                general_dimensions=copy.deepcopy(GENERAL_DIMENSIONS),
                is_builtin=True,
            ))
            added += 1
            continue
        if not p.is_builtin:
            continue
        if _content_differs(data, p):
            p.category = data["category"]
            p.summary = data.get("summary")
            p.description = data.get("description")
            p.tags = data.get("tags", [])
            p.professional_dimensions = data["professional_dimensions"]
            p.general_dimensions = copy.deepcopy(GENERAL_DIMENSIONS)
            updated += 1
    if added or updated:
        await db.commit()
        logger.info(
            "[岗位画像] 播种完成：新增 %d 个，更新 %d 个，共 %d 个内置岗位",
            added, updated, len(rows) + added,
        )
    return {"added": added, "updated": updated}
